package com.example.data.model

import java.util.UUID

/**
 * Types of automation actions supported by AgentFlow.
 */
enum class ActionType(val displayName: String, val category: String) {
    OPEN_APP("Open App", "Apps"),
    OPEN_URL("Open Website", "Web"),
    SEARCH_WEB("Search Google", "Web"),
    MAKE_CALL("Make Phone Call", "Phone"),
    SEND_SMS("Send Text Message", "Messages"),
    NAVIGATE("Get Directions", "Maps"),
    SET_ALARM("Set Alarm", "Clock"),
    SET_TIMER("Start Timer", "Clock"),
    PLAY_MUSIC("Play Music/Video", "Media"),
    OPEN_SETTINGS("Open Settings", "Device"),
    TOGGLE_FLASHLIGHT("Toggle Flashlight", "Hardware"),
    COPY_CLIPBOARD("Copy to Clipboard", "Productivity"),
    CALENDAR_EVENT("Add Calendar Event", "Calendar"),
    SPEAK("Speak Response", "Voice"),
    DEVICE_INFO("Get Device Status", "Device")
}

/**
 * Execution status for each step in an agentic plan.
 */
enum class StepStatus {
    PENDING,
    WAITING_CONFIRMATION,
    RUNNING,
    SUCCESS,
    FAILED,
    SKIPPED
}

/**
 * A concrete automated action step parsed from Gemini's plan or routine.
 */
data class AutomatedActionStep(
    val id: String = UUID.randomUUID().toString(),
    val actionType: ActionType,
    val description: String,
    val packageName: String? = null,
    val appName: String? = null,
    val query: String? = null,
    val url: String? = null,
    val phoneNumber: String? = null,
    val messageText: String? = null,
    val location: String? = null,
    val hour: Int? = null,
    val minute: Int? = null,
    val seconds: Int? = null,
    val settingsType: String? = null,
    val enableToggle: Boolean = true,
    var status: StepStatus = StepStatus.PENDING,
    var resultMessage: String? = null
)

/**
 * Full execution plan generated by Gemini AI for a complex request.
 */
data class AgentPlan(
    val id: String = UUID.randomUUID().toString(),
    val userGoal: String,
    val thoughtProcess: String,
    val steps: List<AutomatedActionStep>,
    val timestamp: Long = System.currentTimeMillis(),
    val isCompleted: Boolean = false
)

/**
 * Custom Voice Command Routine.
 * e.g. "Trigger phrase: 'Morning Briefing' -> Launches weather, news, turns on light"
 */
data class VoiceRoutine(
    val id: String = UUID.randomUUID().toString(),
    val title: String,
    val triggerPhrase: String,
    val promptCommand: String,
    val iconName: String = "Bolt",
    val colorHex: String = "#38BDF8",
    val isEnabled: Boolean = true,
    val isPreset: Boolean = false
)

/**
 * Discovered installed application on the device.
 */
data class InstalledAppInfo(
    val appName: String,
    val packageName: String,
    val isSystemApp: Boolean = false
)

/**
 * Execution log item for user inspection.
 */
data class ExecutionLog(
    val id: String = UUID.randomUUID().toString(),
    val timestamp: Long = System.currentTimeMillis(),
    val level: LogLevel = LogLevel.INFO,
    val tag: String,
    val message: String
)

enum class LogLevel {
    INFO,
    SUCCESS,
    WARNING,
    ERROR
}
